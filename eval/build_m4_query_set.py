"""Build the M4 retrieval test set with Gemini (run once; the output is saved).

    python -m eval.build_m4_query_set

For every case in the library, Gemini sees ONLY the case title and the event
year and writes 4 short messages a stressed traveller might type *today*, in
their own words. The messages are saved to ``eval/data/m4_generated_queries.json``
with a fixed split:

* messages 1-2 -> ``dev``  (the developer may look at failures and tune on these)
* messages 3-4 -> ``test`` (reported, never used for tuning)

Why: the developer wrote the cases, so developer-written queries are biased.
Gemini writing from the title alone is a fairer, independent check, and the
dev/test split keeps the reported score honest even after tuning.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

OUT = Path(__file__).parent / "data" / "m4_generated_queries.json"
MODEL = "gemini-3.5-flash-lite"

PROMPT = """You help build a test set for a travel-disruption assistant.
A past disruption is described ONLY by this title: "{title}" (year {year}).

Write 4 different short messages (one sentence each, max 25 words) that a
stressed US traveller might type to a travel assistant if a SIMILAR problem
were happening to them TODAY. Rules:
- Write in everyday words, like a real person. Vary the style.
- Do NOT copy phrases from the title; paraphrase. Do not mention the year.
- Message 1 and 2 may name the city or airport; message 3 should describe the
  problem without naming the exact airline or aircraft model; message 4 should
  focus on what the traveller is worried about (deadline, connection, etc.).
Return JSON only: {{"queries": ["...", "...", "...", "..."]}}"""


def main() -> None:
    from google import genai
    from google.genai import types

    from travel_agent.hitl.adk_helpers import load_api_key
    from travel_agent.memory import cases

    if not load_api_key():
        raise SystemExit("No Gemini key (.env or GOOGLE_API_KEY).")
    client = genai.Client()
    rows = []
    for case in cases.load_seed_cases():
        year = str(case.get("event_date") or "")[:4]
        for attempt in range(4):
            try:
                response = client.models.generate_content(
                    model=MODEL,
                    contents=PROMPT.format(title=case["title"], year=year),
                    config=types.GenerateContentConfig(response_mime_type="application/json", temperature=0.9),
                )
                queries = json.loads(response.text)["queries"][:4]
                break
            except Exception as exc:  # rate limits / malformed JSON
                if attempt == 3:
                    raise
                print("  retry:", str(exc)[:80])
                time.sleep(15 * (attempt + 1))
        for index, query in enumerate(queries, start=1):
            rows.append({"query": str(query).strip(), "expected_case": case["id"],
                         "split": "dev" if index <= 2 else "test", "style": index})
        print(f"  {case['id']}: {len(queries)} queries")
        time.sleep(2)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps({
        "_about": "Generated by eval/build_m4_query_set.py with " + MODEL + " from case titles only. "
                  "'dev' rows may be used for tuning; 'test' rows are only reported.",
        "queries": rows}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} queries to {OUT}")


if __name__ == "__main__":
    main()
