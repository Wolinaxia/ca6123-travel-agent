"""Round 2 of the M4 retrieval test set (run once; the output is saved).

    python -m eval.build_m4_query_set_round2

Why a second round: in round 1 (``eval/build_m4_query_set.py``) the *dev* half
only had messages that name the airport, while the *test* half only had
messages that do not. Tuning on dev therefore said little about test.

Round 2 fixes that. For every case Gemini again sees ONLY the title and year
and writes 8 messages, two of each style:

1. names the city or airport;
2. names the city or airport, different traveller;
3. describes the problem without naming the airline / aircraft;
4. only says what the traveller is worried about.

One message of each style goes to ``dev2`` (tuning allowed) and the other to
``test2`` (never looked at while tuning; reported once). The round-1 test set is
also kept and reported unchanged, so earlier numbers stay comparable.

Output: ``eval/data/m4_generated_queries_round2.json``.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

OUT = Path(__file__).parent / "data" / "m4_generated_queries_round2.json"
MODEL = "gemini-3.5-flash-lite"

PROMPT = """You are writing test messages for a travel-disruption assistant.
A past disruption is known ONLY by this title: "{title}" (year {year}).

Imagine the SAME KIND of problem is happening TODAY. Write 8 messages a real US
traveller might send, one sentence each (max 25 words). Use different people
(business traveller, parent with kids, student, older traveller, ...) and vary
the tone; a typo or two is fine. Do NOT copy phrases from the title and do not
mention the year.
- Messages 1 and 2: may name the city or airport.
- Messages 3 and 4: describe what is going wrong, without naming the airline or aircraft model.
- Messages 5 and 6: say only what the traveller is worried about (a deadline,
  a connection, an event), with at most a vague hint of the cause.
- Messages 7 and 8: like 1 and 2 but from a different kind of traveller.
Return JSON only: {{"queries": ["...", "...", "...", "...", "...", "...", "...", "..."]}}"""

# message index (1-based) -> (style, split)
LAYOUT = {1: (1, "dev2"), 7: (2, "dev2"), 3: (3, "dev2"), 5: (4, "dev2"),
          2: (1, "test2"), 8: (2, "test2"), 4: (3, "test2"), 6: (4, "test2")}


def main() -> None:
    from google import genai
    from google.genai import types

    from travel_agent.hitl.adk_helpers import load_api_key
    from travel_agent.memory import cases

    if not load_api_key():
        raise SystemExit("No Gemini key (.env or GOOGLE_API_KEY).")
    client = genai.Client()
    rows = []
    for case in cases.load_seed_cases():
        year = str(case.get("event_date") or "")[:4]
        for attempt in range(5):
            try:
                response = client.models.generate_content(
                    model=MODEL,
                    contents=PROMPT.format(title=case["title"], year=year),
                    config=types.GenerateContentConfig(response_mime_type="application/json", temperature=1.0),
                )
                queries = json.loads(response.text)["queries"]
                if len(queries) < 8:
                    raise ValueError(f"only {len(queries)} queries")
                break
            except Exception as exc:  # rate limits / malformed JSON
                if attempt == 4:
                    raise
                print("  retry:", str(exc)[:80])
                time.sleep(15 * (attempt + 1))
        for index, query in enumerate(queries[:8], start=1):
            style, split = LAYOUT[index]
            rows.append({"query": str(query).strip(), "expected_case": case["id"], "split": split, "style": style})
        print(f"  {case['id']}: 8 queries", flush=True)
        time.sleep(2)
    OUT.write_text(json.dumps({
        "_about": "Round 2, generated by eval/build_m4_query_set_round2.py with " + MODEL + " from case titles only. "
                  "Every split has all 4 styles. 'dev2' may be used for tuning; 'test2' is only reported.",
        "queries": rows}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} queries to {OUT}")


if __name__ == "__main__":
    main()
